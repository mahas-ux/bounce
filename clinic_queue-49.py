# === Stage 49: Добавь финальную самопроверку приложения и отчёт о готовности ===
# Project: ClinicQueue
def self_check():
    """Финальная самопроверка: имитируем 3 типичных сценария и проверяем, что система работает."""
    from clinic_queue import ClinicQueue
    q = ClinicQueue()

    # Сценарий 1: добавление пациента
    p1 = q.add_patient("Иванов И.И.", "2026-07-01 10:00", "Ожидание", "Головная боль")
    assert p1.id is not None, "add_patient не вернул id"
    assert p1.status == "Ожидание", "статус не сохранился"
    assert p1.notes == "Головная боль", "заметка не сохранилась"

    # Сценарий 2: смена статуса
    p1.set_status("Приём")
    assert p1.status == "Приём", "смена статуса не сработала"

    # Сценарий 3: добавление второго пациента и проверка очереди
    p2 = q.add_patient("Петров П.П.", "2026-07-01 10:30", "Ожидание", "Перелом")
    queue = q.get_queue()
    assert len(queue) == 2, "очередь не содержит 2 пациентов"
    assert queue[0].id == p1.id, "первый пациент не на первом месте"
    assert queue[1].id == p2.id, "второй пациент не на втором месте"

    # Сценарий 4: обновление заметки
    p1.update_notes("Головная боль, давление 120/80")
    assert "давление" in p1.notes, "обновление заметки не сработало"

    # Сценарий 5: завершение приёма
    p1.set_status("Завершён")
    assert p1.status == "Завершён", "статус не завершён"

    # Сценарий 6: удаление пациента
    p2 = q.get_patient(p2.id)
    q.remove_patient(p2.id)
    assert q.get_patient(p2.id) is None, "удаление не сработало"
    assert len(q.get_queue()) == 1, "после удаления не 1 пациент"

    # Сценарий 7: генерация отчёта
    report = q.generate_report()
    assert report is not None, "отчёт не сгенерирован"
    assert "Иванов" in report, "отчёт не содержит данных о первом пациенте"

    print("✅ Все 7 сценариев прошли успешно. Приложение готово к использованию.")
    return True

if __name__ == "__main__":
    self_check()
